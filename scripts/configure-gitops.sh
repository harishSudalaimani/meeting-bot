#!/usr/bin/env bash
set -euo pipefail
repo_root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
infra="$repo_root/terraform/environments/learning"
tag=${1:-}
if [[ -z "$tag" ]]; then echo "usage: $0 <immutable-image-tag>" >&2; exit 2; fi
region=$(terraform -chdir="$infra" output -raw region)
api_host=$(terraform -chdir="$infra" output -raw api_hostname)
cert=$(terraform -chdir="$infra" output -raw api_certificate_arn)
waf=$(terraform -chdir="$infra" output -raw waf_arn)
repos=$(terraform -chdir="$infra" output -json ecr_repositories)
api_repo=$(jq -r '.value.api' <<<"$repos")
controller_repo=$(jq -r '.value.controller' <<<"$repos")
bot_repo=$(jq -r '.value["meeting-bot"]' <<<"$repos")
delivery_repo=$(jq -r '.value["delivery-worker"]' <<<"$repos")
cat >"$repo_root/kubernetes/chart/values-learning.yaml" <<EOF
# Generated by scripts/configure-gitops.sh. Contains identifiers, never credentials.
images:
  api: ${api_repo}:${tag}
  controller: ${controller_repo}:${tag}
  meetingBot: ${bot_repo}:${tag}
  deliveryWorker: ${delivery_repo}:${tag}
edge:
  hostname: ${api_host}
  certificateArn: ${cert}
  wafArn: ${waf}
  apiReplicas: 1
  controllerReplicas: 1
observability:
  region: ${region}
  collectorImage: public.ecr.aws/aws-observability/aws-otel-collector:v0.50.0
EOF
echo "Updated kubernetes/chart/values-learning.yaml for $api_host. Review and commit it for Argo CD."
